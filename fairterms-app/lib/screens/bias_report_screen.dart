class _Gauge extends StatefulWidget {
  final int score;
  final Color color;
  final AnimationController animation;

  const _Gauge({
    required this.score,
    required this.color,
    required this.animation,
  });

  @override
  State<_Gauge> createState() => _GaugeState();
}

class _GaugeState extends State<_Gauge> {
  late Animation<double> _scoreAnim;

  @override
  void initState() {
    super.initState();
    _scoreAnim = Tween<double>(begin: 0, end: widget.score.toDouble()).animate(
        CurvedAnimation(parent: widget.animation, curve: Curves.easeOut));
  }

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: 240,
      height: 240,
      child: Stack(
        alignment: Alignment.center,
        children: [
          AnimatedBuilder(
            animation: _scoreAnim,
            builder: (ctx, _) {
              return CustomPaint(
                size: Size(240, 240),
                painter: _GaugePainter(
                  score: _scoreAnim.value,
                  color: widget.color,
                ),
              );
            },
          ),
          Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              AnimatedBuilder(
                animation: _scoreAnim,
                builder: (ctx, _) {
                  return Text(
                    '${_scoreAnim.value.toInt()}',
                    style: GoogleFonts.fraunces(
                      fontSize: 76,
                      fontWeight: FontWeight.w300,
                      letterSpacing: -0.04,
                      color: AppColors.ink,
                    ),
                  );
                },
              ),
              SizedBox(height: 6),
              Text(
                '/ 100 · ${widget.color == AppColors.error ? 'severe' : widget.color == AppColors.warning ? 'moderate' : 'fair'}',
                style: GoogleFonts.inter(
                  fontSize: 11,
                  letterSpacing: 0.12,
                  color: AppColors.inkFaint,
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}

class _GaugePainter extends CustomPainter {
  final double score;
  final Color color;

  _GaugePainter({required this.score, required this.color});

  @override
  void paint(Canvas canvas, Size size) {
    final center = Offset(size.width / 2, size.height / 2);
    const radius = 100.0;
    const strokeWidth = 14.0;

    // Track (cream)
    final trackPaint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth
      ..strokeCap = StrokeCap.round
      ..color = AppColors.outline;

    canvas.drawCircle(center, radius, trackPaint);

    // Arc (colored)
    final arcPaint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth
      ..strokeCap = StrokeCap.round
      ..color = color;

    final sweepAngle = 2 * math.pi * (score.clamp(0, 100) / 100);
    canvas.drawArc(
      Rect.fromCircle(center: center, radius: radius),
      -math.pi / 2,
      sweepAngle,
      false,
      arcPaint,
    );
  }

  @override
  bool shouldRepaint(_GaugePainter old) =>
      old.score != score || old.color != color;
}

