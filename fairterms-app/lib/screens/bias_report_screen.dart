class BiasReportScreen extends ConsumerStatefulWidget {
  final String analysisId;
  const BiasReportScreen({super.key, required this.analysisId});

  @override
  ConsumerState<BiasReportScreen> createState() => _BiasReportScreenState();
}

class _BiasReportScreenState extends ConsumerState<BiasReportScreen>
    with TickerProviderStateMixin {
  BiasReport? _report;
  bool _isLoading = true;
  bool _isGeneratingPdf = false;
  String? _error;
  late AnimationController _gaugeCtrl;
  final List<AnimationController> _sectionCtrls = [];

  @override
  void initState() {
    super.initState();
    _gaugeCtrl = AnimationController(
        duration: const Duration(milliseconds: 900), vsync: this);
    _loadReport();
  }

  Future<void> _loadReport() async {
    final analysisState = ref.read(analysisProvider);
    if (analysisState.report != null) {
      if (mounted) {
        setState(() {
          _report = analysisState.report;
          _isLoading = false;
          _gaugeCtrl.forward();
        });
      }
      return;
    }

    try {
      final report =
          await ApiService.instance.getAnalysisReport(widget.analysisId);
      if (mounted) {
        setState(() {
          _report = report;
          _isLoading = false;
          _gaugeCtrl.forward();
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _error = e.toString();
          _isLoading = false;
        });
      }
    }
  }

  Future<void> _downloadGrievancePdf() async {
    setState(() => _isGeneratingPdf = true);
    try {
      final data = await ApiService.instance.getGrievanceData(widget.analysisId);
      await _performPdfDownload(data);
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to generate PDF: $e'),
            backgroundColor: AppColors.error,
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _isGeneratingPdf = false);
    }
  }

  Future<void> _performPdfDownload(GrievanceData data) async {
    try {
      await Printing.layoutPdf(
        name: 'fairterms_grievance_${widget.analysisId}.pdf',
        onLayout: (PdfPageFormat format) async {
          final doc = pw.Document();
          doc.addPage(
            pw.MultiPage(
              pageFormat: format,
              margin: const pw.EdgeInsets.all(48),
              build: (pw.Context ctx) => [
                pw.Text(
                  data.grievanceLetter.subject,
                  style: pw.TextStyle(
                    fontSize: 18,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 24),
                pw.Text(
                  data.grievanceLetter.body,
                  style: const pw.TextStyle(fontSize: 11, lineSpacing: 4),
                ),
                pw.SizedBox(height: 48),
                pw.Divider(thickness: 1, color: PdfColors.grey300),
                pw.SizedBox(height: 12),
                pw.Text(
                  'Generated by FairTerms AI Analysis • ${DateFormat('dd MMM yyyy').format(DateTime.now())}',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                ),
              ],
            ),
          );
          return doc.save();
        },
      );
    } catch (e) {
      debugPrint('PDF layout error: $e');
    }
  }

  @override
  void dispose() {
    _gaugeCtrl.dispose();
    for (final ctrl in _sectionCtrls) {
      ctrl.dispose();
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    if (_isLoading) {
      return Scaffold(
        backgroundColor: AppColors.background,
        body: Center(
          child: CircularProgressIndicator(color: AppColors.primary),
        ),
      );
    }

    if (_error != null) {
      return Scaffold(
        backgroundColor: AppColors.background,
        body: Center(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Icon(Icons.error_outline, color: AppColors.error, size: 48),
              SizedBox(height: 16),
              Text('Failed to load report',
                  style:
                      GoogleFonts.fraunces(fontSize: 18, color: AppColors.ink)),
              SizedBox(height: 8),
              Text(_error!,
                  style: GoogleFonts.inter(color: AppColors.inkMuted)),
              SizedBox(height: 16),
              ElevatedButton(
                onPressed: () {
                  setState(() {
                    _isLoading = true;
                    _error = null;
                  });
                  _loadReport();
                },
                child: Text('Retry'),
              ),
            ],
          ),
        ),
      );
    }

    final report = _report!;
    final score = report.overallFairnessScore.toInt();
    final isSevere = score < 41;
    final isModerate = score >= 41 && score < 71;

    Color eyebrowColor = AppColors.primary;
    String eyebrowLabel = 'Fair terms';
    if (isSevere) {
      eyebrowColor = AppColors.error;
      eyebrowLabel = 'Severe bias detected';
    } else if (isModerate) {
      eyebrowColor = AppColors.warning;
      eyebrowLabel = 'Moderate bias detected';
    }
    return LoadingOverlay(
      isLoading: _isGeneratingPdf,
      message: 'Generating PDF document...',
      child: Scaffold(
        backgroundColor: AppColors.background,
        body: Column(
          children: [
            _TopBar(),
            Expanded(
              child: SingleChildScrollView(
                child: Column(
                  children: [
                    Padding(
                      padding: EdgeInsets.symmetric(horizontal: 40, vertical: 24),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                            'Dashboard  /  Analyses  /  ${report.analysisId}',
                            style: GoogleFonts.inter(
                              fontSize: 12,
                              color: AppColors.inkFaint,
                              letterSpacing: 0.02,
                            ),
                          ),
                          SizedBox(height: 20),
                          Row(
                            crossAxisAlignment: CrossAxisAlignment.end,
                            mainAxisAlignment: MainAxisAlignment.spaceBetween,
                            children: [
                              Expanded(
                                child: Column(
                                  crossAxisAlignment: CrossAxisAlignment.start,
                                  children: [
                                    Text(
                                      eyebrowLabel,
                                      style: GoogleFonts.inter(
                                        fontSize: 11,
                                        fontWeight: FontWeight.w500,
                                        letterSpacing: 0.14,
                                        color: eyebrowColor,
                                      ),
                                    ),
                                    SizedBox(height: 14),
                                    Text(
                                      report.analysisId,
                                      style: GoogleFonts.fraunces(
                                        fontSize: 56,
                                        fontWeight: FontWeight.w300,
                                        letterSpacing: -0.03,
                                        color: AppColors.ink,
                                        height: 1.02,
                                      ),
                                    ),
                                    SizedBox(height: 16),
                                    Text(
                                      '${report.explanation.paragraphs.isNotEmpty ? report.explanation.paragraphs.first : "Analysis from ${report.analysisId}"} • Analysed on ${_fmtDate(DateTime.now())}',
                                      style: GoogleFonts.inter(
                                        fontSize: 14,
                                        color: AppColors.inkMuted,
                                        height: 1.55,
                                      ),
                                      maxLines: 3,
                                    ),
                                  ],
                                ),
                              ),
                              Row(
                                mainAxisSize: MainAxisSize.min,
                                children: [
                                  _GhostBtn(
                                    label: 'Share',
                                    onPressed: () {
                                      final url = Uri.base
                                          .resolve('/analysis/${widget.analysisId}/report')
                                          .toString();
                                      Clipboard.setData(ClipboardData(text: url));
                                      ScaffoldMessenger.of(context).showSnackBar(
                                        const SnackBar(content: Text('Report link copied to clipboard')),
                                      );
                                    },
                                  ),
                                  SizedBox(width: 8),
                                  _SolidBtn(
                                    label: 'Download PDF',
                                    onPressed: _downloadGrievancePdf,
                                  ),
                                ],
                              ),
                            ],
                          ),
                          Divider(
                            color: AppColors.outline,
                            height: 64,
                            thickness: 1,
                          ),
                          _HeroSection(
                            score: score,
                            eyebrowColor: eyebrowColor,
                            verdict: report.explanation.headline,
                            description: report.explanation.paragraphs.length > 1
                                ? report.explanation.paragraphs[1]
                                : report.explanation.paragraphs.isNotEmpty
                                    ? report.explanation.paragraphs[0]
                                    : 'Analysis computed.',
                            factors: report.biasFactors,
                            gaugeCtrl: _gaugeCtrl,
                          ),
                          SizedBox(height: 64),
                          _FactorSection(factors: report.biasFactors),
                          SizedBox(height: 64),
                          _BenchmarkSection(
                              benchmarks: report.benchmarkComparison),
                          SizedBox(height: 64),
                          if (report.interestCalculation != null)
                            _InterestSection(
                                interest: report.interestCalculation!),
                          if (report.interestCalculation != null)
                            SizedBox(height: 64),
                          if (report.taxAlert != null)
                            _TaxAlertSection(alert: report.taxAlert!),
                          if (report.taxAlert != null) SizedBox(height: 64),
                          _ActionSection(
                            analysisId: widget.analysisId,
                            onDownloadPdf: _downloadGrievancePdf,
                          ),
                          SizedBox(height: 80),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  String _fmtDate(DateTime dt) => DateFormat('dd MMMM yyyy').format(dt);
}

