class _FactorSection extends StatelessWidget {
  final List<BiasFactor> factors;

  const _FactorSection({required this.factors});

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          "What's driving the score",
          style: GoogleFonts.fraunces(
            fontSize: 24,
            fontWeight: FontWeight.w400,
            letterSpacing: -0.02,
            color: AppColors.ink,
          ),
        ),
        SizedBox(height: 20),
        Container(
          padding: EdgeInsets.all(28),
          decoration: BoxDecoration(
            border: Border.all(color: AppColors.outline, width: 1),
            borderRadius: BorderRadius.circular(12),
            color: AppColors.background,
          ),
          child: Column(
            children: factors.isEmpty
                ? [
                    Text(
                      'No factors flagged.',
                      style: GoogleFonts.inter(color: AppColors.inkFaint),
                    ),
                  ]
                : factors.asMap().entries.map((e) {
                    final f = e.value;
                    final isLast = e.key == factors.length - 1;
                    final weight = (f.impactScore * 25).toInt();

                    Color barColor = AppColors.primary;
                    if (f.impactScore > 0.66) {
                      barColor = AppColors.error;
                    } else if (f.impactScore > 0.33) {
                      barColor = AppColors.warning;
                    }

                    return Column(
                      children: [
                        Padding(
                          padding: EdgeInsets.symmetric(vertical: 20),
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Row(
                                mainAxisAlignment:
                                    MainAxisAlignment.spaceBetween,
                                children: [
                                  Text(
                                    f.factor,
                                    style: GoogleFonts.fraunces(
                                      fontSize: 18,
                                      fontWeight: FontWeight.w400,
                                      letterSpacing: -0.01,
                                      color: AppColors.ink,
                                    ),
                                  ),
                                  Text(
                                    'weight $weight%',
                                    style: GoogleFonts.jetBrainsMono(
                                      fontSize: 11,
                                      color: AppColors.inkFaint,
                                    ),
                                  ),
                                ],
                              ),
                              SizedBox(height: 6),
                              Text(
                                f.detail,
                                style: GoogleFonts.inter(
                                  fontSize: 13,
                                  color: AppColors.inkMuted,
                                  height: 1.6,
                                ),
                              ),
                              SizedBox(height: 14),
                              ClipRRect(
                                borderRadius: BorderRadius.circular(4),
                                child: Container(
                                  height: 6,
                                  color: AppColors.surface,
                                  child: FractionallySizedBox(
                                    widthFactor: f.impactScore.clamp(0, 1),
                                    alignment: Alignment.centerLeft,
                                    child: Container(color: barColor),
                                  ),
                                ),
                              ),
                            ],
                          ),
                        ),
                        if (!isLast)
                          Divider(
                            color: AppColors.outline,
                            height: 1,
                            thickness: 1,
                          ),
                      ],
                    );
                  }).toList(),
          ),
        ),
      ],
    );
  }
